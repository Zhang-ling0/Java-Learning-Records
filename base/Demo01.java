package base;

public class Demo01 {
    public static void main(String[] args){
        //八大基本数据类型，强类型语言体现在，所有变量的定义必须符合规范

        //整数
        int num1 =10;//最常用
        byte num2 = 20;
        short num3 = 30;
        long num4 = 30L;//Long类型要在数字后面加L

        //小数：浮点数
        float num5 = 2.22F;//Lfloat类型要在数字后面加个F
        double num6 = 3.1415926;

        //字符型
        char name1 = '张';//字符只能是一个

        //字符串，String不是关键字，是类
        String name2 = "张玲";

        //布尔值：是非
        boolean flag1 = true;
        boolean flag2 = false;

    }
}
